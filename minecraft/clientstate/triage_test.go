// triage classifies a clientbound packet's relationship to a server swap.
type triage uint8

const (
	// triageTracked: Observe mirrors it and ClearPackets removes it.
	triageTracked triage = iota
	// triageSwept: state ClearPackets clears unconditionally (titles, forms, inventory).
	triageSwept
	// triageRestored: re-derived from GameData by the swap flow, or re-established by
	// the replacement's own join sequence (world content, registries, rules).
	triageRestored
	// triageGap: outlives a swap but is deliberately untracked (camera, HUD, fog, debug
	// shapes, looping sounds); a swap flow owns whichever of these it cares about.
	triageGap
	// triageTransient: leaves no client-visible state that outlives a swap.
	triageTransient
)

var triageNames = map[triage]string{
	triageTracked: "tracked", triageSwept: "swept", triageRestored: "restored",
	triageGap: "gap", triageTransient: "transient",
}

