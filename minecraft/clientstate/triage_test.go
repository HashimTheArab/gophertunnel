// A new server-pool packet must be classified, and the manifest must agree with Tracked.
func TestServerPoolTriaged(t *testing.T) {
	pool := packet.NewServerPool()
	for id, mk := range pool {
		tri, ok := serverPacketTriage[id]
		if !ok {
			t.Errorf("%T (ID %d) is not classified in serverPacketTriage; if it creates client state that outlives a server swap, track it", mk(), id)
			continue
		}
		if got := Tracked(mk()); got != (tri == triageTracked) {
			t.Errorf("Tracked(%T) = %t, but the manifest classifies it %q", mk(), got, triageNames[tri])
		}
	}
	for id := range serverPacketTriage {
		if _, ok := pool[id]; !ok {
			t.Errorf("manifest entry for packet ID %d is no longer in the server pool; remove it", id)
		}
	}
}
